"""Regenerate sql/02_sample_data.sql (fictional sample data, fixed seed).

All names are invented. No real customers or personal data.
Usage: python scripts/generate_data.py
"""
import random
from datetime import date, timedelta
from pathlib import Path

random.seed(2025)
OUT = Path(__file__).resolve().parents[1] / "sql" / "02_sample_data.sql"

FIRST = ["Aarav", "Diya", "Kiran", "Meera", "Rohan", "Sneha", "Vikram", "Ananya", "Arjun", "Kavya",
         "Rahul", "Priya", "Nikhil", "Lakshmi", "Suresh", "Divya", "Harsha", "Pooja", "Teja", "Swathi"]
LAST = ["R.", "K.", "S.", "M.", "P.", "V.", "N.", "T."]
CITIES = ["Tirupati", "Hyderabad", "Bengaluru", "Chennai", "Vijayawada", "Visakhapatnam", "Pune", "Mumbai"]
PRODUCTS = [
    ("Wireless Earbuds", "Electronics", 1999.00), ("Bluetooth Speaker", "Electronics", 2499.00),
    ("USB-C Charger 30W", "Electronics", 899.00), ("Smart Watch", "Electronics", 3499.00),
    ("Laptop Backpack", "Accessories", 1299.00), ("Phone Case", "Accessories", 349.00),
    ("Cotton T-Shirt", "Apparel", 499.00), ("Running Shoes", "Apparel", 2799.00),
    ("Denim Jacket", "Apparel", 1899.00), ("Steel Water Bottle", "Home & Kitchen", 599.00),
    ("Non-stick Pan", "Home & Kitchen", 1149.00), ("Coffee Mug Set", "Home & Kitchen", 649.00),
    ("Desk Lamp", "Home & Kitchen", 899.00), ("Python Crash Course (book)", "Books", 1450.00),
    ("SQL Pocket Guide (book)", "Books", 750.00), ("Notebook Pack", "Stationery", 249.00),
    ("Gel Pen Set", "Stationery", 199.00), ("Yoga Mat", "Sports", 999.00),
    ("Cricket Bat", "Sports", 2299.00), ("Resistance Bands", "Sports", 699.00),
]
METHODS = ["UPI", "Credit Card", "Debit Card", "Net Banking", "Cash on Delivery"]
METHOD_W = [45, 20, 15, 8, 12]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


lines = ["-- Fictional sample data generated by scripts/generate_data.py (seed=2025).", ""]

customers = []
for cid in range(1, 41):
    name = f"{random.choice(FIRST)} {random.choice(LAST)}"
    signup = date(2024, 6, 1) + timedelta(days=random.randint(0, 210))
    customers.append((cid, name, random.choice(CITIES), signup))
lines.append("INSERT INTO customers (customer_id, full_name, city, signup_date) VALUES")
lines.append(",\n".join(f"  ({c}, {q(n)}, {q(ci)}, {q(d)})" for c, n, ci, d in customers) + ";\n")

lines.append("INSERT INTO products (product_id, product_name, category, list_price) VALUES")
lines.append(",\n".join(f"  ({i}, {q(n)}, {q(c)}, {p:.2f})" for i, (n, c, p) in enumerate(PRODUCTS, 1)) + ";\n")

# A skewed purchase frequency so that some customers are repeat buyers and some buy once.
weights = [random.choice([1, 1, 1, 2, 3, 5]) for _ in customers]
orders, items, payments = [], [], []
item_id = pay_id = 1
for oid in range(1, 221):
    cid = random.choices([c[0] for c in customers], weights=weights)[0]
    signup = customers[cid - 1][3]
    start = max(signup, date(2025, 1, 1))
    odate = start + timedelta(days=random.randint(0, (date(2025, 12, 31) - start).days))
    status = random.choices(["delivered", "shipped", "cancelled", "returned"], [78, 8, 8, 6])[0]
    orders.append((oid, cid, odate, status))

    total = 0.0
    for pid in random.sample(range(1, len(PRODUCTS) + 1), k=random.choices([1, 2, 3], [55, 30, 15])[0]):
        qty = random.choices([1, 2, 3], [75, 20, 5])[0]
        price = PRODUCTS[pid - 1][2]
        if random.random() < 0.2:          # occasional sale discount (price at time of sale)
            price = round(price * 0.9, 2)
        items.append((item_id, oid, pid, qty, price))
        item_id += 1
        total += qty * price
    total = round(total, 2)

    pstatus = "refunded" if status in ("cancelled", "returned") else "completed"
    method = random.choices(METHODS, METHOD_W)[0]
    if method != "Cash on Delivery" and total > 1500 and random.random() < 0.25:
        wallet = 200.00                     # split payment: wallet credit + main method
        payments.append((pay_id, oid, "Wallet", wallet, pstatus, odate)); pay_id += 1
        payments.append((pay_id, oid, method, round(total - wallet, 2), pstatus, odate)); pay_id += 1
    else:
        payments.append((pay_id, oid, method, total, pstatus, odate)); pay_id += 1

lines.append("INSERT INTO orders (order_id, customer_id, order_date, status) VALUES")
lines.append(",\n".join(f"  ({o}, {c}, {q(d)}, {q(s)})" for o, c, d, s in orders) + ";\n")
lines.append("INSERT INTO order_items (order_item_id, order_id, product_id, quantity, unit_price) VALUES")
lines.append(",\n".join(f"  ({i}, {o}, {p}, {qt}, {pr:.2f})" for i, o, p, qt, pr in items) + ";\n")
lines.append("INSERT INTO payments (payment_id, order_id, payment_method, amount, payment_status, paid_on) VALUES")
lines.append(",\n".join(f"  ({i}, {o}, {q(m)}, {a:.2f}, {q(s)}, {q(d)})" for i, o, m, a, s, d in payments) + ";\n")

OUT.write_text("\n".join(lines))
print(f"wrote {OUT}: {len(customers)} customers, {len(PRODUCTS)} products, {len(orders)} orders, "
      f"{len(items)} order_items, {len(payments)} payments")
