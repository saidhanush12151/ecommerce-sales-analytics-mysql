"""Load the schema + sample data into an in-memory SQLite database, run every query in
sql/03_analysis_queries.sql, and write the results to outputs/sample_outputs.md.

This is a no-install way to check the SQL and regenerate sample outputs. For MySQL, see README.
Usage: python scripts/run_queries_sqlite.py
"""
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / "sql"


def fmt(v, col):
    if v is None:
        return "NULL"
    if col.endswith("_pct"):
        return f"{v:g}"
    money = any(k in col for k in ("revenue", "value", "amount", "payments", "total"))
    if isinstance(v, float) or (money and isinstance(v, int) and col not in ("payments",)):
        return f"{v:,.2f}" if money else f"{v:g}"
    return str(v)


def main():
    con = sqlite3.connect(":memory:")
    con.execute("PRAGMA foreign_keys = ON")
    con.executescript((SQL / "01_schema.sql").read_text())
    con.executescript((SQL / "02_sample_data.sql").read_text())

    counts = {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
              for t in ("customers", "products", "orders", "order_items", "payments")}

    text = (SQL / "03_analysis_queries.sql").read_text()
    blocks = re.split(r"^-- name: (\S+)\s*$", text, flags=re.M)[1:]
    out = ["# Sample outputs", "",
           f"Generated by `scripts/run_queries_sqlite.py` with SQLite {sqlite3.sqlite_version} "
           "from `sql/01_schema.sql`, `sql/02_sample_data.sql`, and `sql/03_analysis_queries.sql`.", "",
           "Row counts: " + ", ".join(f"{k} = {v}" for k, v in counts.items()), ""]
    for name, body in zip(blocks[::2], blocks[1::2]):
        comments = [l[3:] for l in body.strip().splitlines() if l.startswith("-- ")]
        cur = con.execute(body)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        out += [f"## {name}", ""] + ([" ".join(comments), ""] if comments else [])
        out.append("| " + " | ".join(cols) + " |")
        out.append("|" + "---|" * len(cols))
        for r in rows:
            out.append("| " + " | ".join(fmt(v, c) for v, c in zip(r, cols)) + " |")
        out.append("")
        print(f"{name}: {len(rows)} rows")
    (ROOT / "outputs" / "sample_outputs.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
